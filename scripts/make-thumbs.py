# Makes a 480px-wide WebP copy (name-480.webp) of every image under public/case-studies,
# public/events and public/videos, for places where the image shows small (thumbnails,
# strips, grids) so phones don't download the full-size file. Also writes
# src/data/thumbs.ts, the list of images that have one, which thumbProps() in
# src/lib/img.ts checks before pointing the browser at it.
# Run it after adding images:  python3 scripts/make-thumbs.py   (needs Pillow)
from pathlib import Path
from PIL import Image

WIDTH = 480
roots = [Path('public/case-studies'), Path('public/events'), Path('public/videos')]
made = []
for root in roots:
    for f in sorted(root.rglob('*')):
        if f.suffix.lower() not in ('.webp', '.jpg', '.jpeg', '.png'): continue
        if f.stem.endswith(('-480', '-800')) or f.stem.endswith('-share') or 'large' in f.stem: continue
        out = f.with_name(f.stem + '-480.webp')
        im = Image.open(f)
        small = im.width <= WIDTH * 1.2
        # Already small and already WebP: the original is fine. Small JPEG/PNG files still
        # get a WebP copy at their own size, which is lighter.
        if small and f.suffix.lower() == '.webp': continue
        if not out.exists() or out.stat().st_mtime < f.stat().st_mtime:
            im = im.convert('RGBA' if im.mode in ('RGBA', 'LA', 'P') else 'RGB')
            if not small:
                im = im.resize((WIDTH, round(im.height * WIDTH / im.width)), Image.LANCZOS)
            im.save(out, 'WEBP', quality=78, method=6)
        made.append('/' + str(f.relative_to('public')))

lines = ['// Generated by scripts/make-thumbs.py: images that have a 480px-wide -480.webp copy.',
         'export const thumbs = new Set([']
lines += [f"  '{p}'," for p in made]
lines += ['])', '']
Path('src/data/thumbs.ts').write_text('\n'.join(lines))
print(len(made), 'images have a 480px copy')
